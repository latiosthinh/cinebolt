// Four sprocket holes down the left edge of the triangle (rounded rectangles, r = 9).
function roundRect(x, y, w, h, r) {
  const k = r * 0.5523; // cubic approximation of a quarter circle
  const f = n => +n.toFixed(2);
  return [`M${f(x + r)},${f(y)}`, `H${f(x + w - r)}`, `C${f(x + w - r + k)},${f(y)},${f(x + w)},${f(y + r - k)},${f(x + w)},${f(y + r)}`,
    `V${f(y + h - r)}`, `C${f(x + w)},${f(y + h - r + k)},${f(x + w - r + k)},${f(y + h)},${f(x + w - r)},${f(y + h)}`,
    `H${f(x + r)}`, `C${f(x + r - k)},${f(y + h)},${f(x)},${f(y + h - r + k)},${f(x)},${f(y + h - r)}`,
    `V${f(y + r)}`, `C${f(x)},${f(y + r - k)},${f(x + r - k)},${f(y)},${f(x + r)},${f(y)}`, 'Z'].join('');
}
const holes = [62, 140, 218, 296].map(y => roundRect(24, y, 34, 42, 9)).join('');

const colors = { bg: '#07080b', ember: '#FF5A1F', amber: '#FFB53D', bolt: '#FFFFFF', boltWarm: '#FFE2AE' };
const grad = { tri: [0, 380, 360, 40], bolt: [228, 18, 137, 308] };
fs.writeFileSync(path.join(__dirname, 'logo-paths.json'), JSON.stringify({ triangle, holes, boltShadow, bolt, colors, grad }, null, 2));

// --- Web SVG (also used as favicon and in-app brand) ---
